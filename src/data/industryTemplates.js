/** テンプレートからプロジェクトを生成（Step0・Step1・Step3も初期化） */
export function createFromTemplate(template) {
  const proj = createInitialProject();
  proj.settings.marketType = template.marketType;
  proj.settings.productService = template.preset.productService;

  // Step0: バリューチェーン項目・カテゴリ名を業種別にカスタマイズ
  const vcItems = template.preset.valueChainItems;
  const vcCats = template.preset.valueChainCategories;
  if (vcItems || vcCats) {
    proj.step0.categories = VALUE_CHAIN_CATEGORIES.map(cat => {
      const customItems = vcItems?.[cat.id] || cat.items;
      const catOverride = vcCats?.[cat.id] || {};
      return {
        id: cat.id,
        categoryName: catOverride.name || cat.name,
        categoryDescription: catOverride.description || cat.description,
        categoryType: catOverride.type || cat.type,
        items: customItems.map((name, idx) => ({
          id: `${cat.id}_${idx}`,
          name,
          strength: '',
          communication: '',
          communicationStatus: '',
          isStrengthFlag: false,
          isCustom: false,
        })),
      };
    });
  }

  // Step1: セグメント軸をプリセット
  const segmentMaster = template.marketType === 'btob' ? BTOB_SEGMENTS : BTOC_SEGMENTS;
  const selectedAxes = (template.preset.suggestedAxes || []).map(axisId => {
    const master = segmentMaster.find(s => s.id === axisId);
    if (!master) return null;
    return { ...master, priority: 'high' };
  }).filter(Boolean);
  proj.step1.selectedAxes = selectedAxes;

  // Step1: 各軸の推奨セグメントを初期値として設定
  const suggestedSegments = template.preset.suggestedSegments || {};
  const segments = {};
  for (const [axisId, names] of Object.entries(suggestedSegments)) {
    segments[axisId] = names.map((name, i) => ({
      id: `seg_tmpl_${axisId}_${i}`,
      name,
      memo: '',
    }));
  }
  proj.step1.segments = segments;

  // Step3: ポジショニング軸をプリセット
  if (template.preset.positioningAxes) {
    proj.step3.axes = template.preset.positioningAxes.map((name, idx) => ({
      id: `pa_${idx}`,
      name,
    }));
  }

  return proj;
}
